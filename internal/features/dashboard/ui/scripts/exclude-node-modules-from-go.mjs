// task 183: keep the Go toolchain out of the installed JS dependencies.
//
// `go build/test/vet ./...` walks the whole module tree and DOES descend into
// node_modules (verified on go1.26: a stray *.go anywhere under node_modules is
// compiled and can break the build). node_modules is gitignored, so we cannot
// commit a marker into it — but a lone `go.mod` turns any directory into a
// nested-module boundary that the parent module's `./...` walk skips entirely.
//
// This runs as npm's `postinstall`, so the marker is (re)created after every
// `npm install` / `npm ci` (which wipes and repopulates node_modules). Because
// node_modules is gitignored, the marker never dirties the working tree, so
// goreleaser's clean-tree check and the `go:embed all:ui/dist` bundle (a
// sibling of node_modules, not under it) are both unaffected.
import { writeFileSync, existsSync, mkdirSync } from 'node:fs'
import { fileURLToPath } from 'node:url'
import { dirname, join } from 'node:path'

// scripts/ lives at ui/scripts, so node_modules is one level up.
const uiDir = dirname(dirname(fileURLToPath(import.meta.url)))
const nodeModules = join(uiDir, 'node_modules')

// postinstall runs after node_modules is populated; create it defensively so a
// direct `node scripts/...` invocation before install still writes the marker.
if (!existsSync(nodeModules)) mkdirSync(nodeModules, { recursive: true })

const marker = `// Generated by ui/scripts/exclude-node-modules-from-go.mjs (task 183).
// This directory holds installed JS dependencies, not Go code. This lone go.mod
// makes it a nested-module boundary so the parent module's \`go build/test/vet
// ./...\` skips the entire subtree instead of compiling vendored JavaScript.
// Not committed (node_modules is gitignored); regenerated by npm postinstall.
module dacli.dev/dashboard-ui/node_modules-not-go

go 1.22
`

writeFileSync(join(nodeModules, 'go.mod'), marker)
